function attributeOf(node, name) {
  const attribute = node.attributes.find((candidate) => candidate.key.value === name)

  if (attribute === undefined) {
    return {kind: "absent"}
  }

  // A bare attribute, such as `hidden`, has no value.
  if (attribute.value === undefined) {
    return {kind: "present", value: ""}
  }

  return {kind: "present", value: attribute.value.value}
}

function hasAttribute(node, name) {
  return attributeOf(node, name).kind === "present"
}

function isAttributeValue({node, name, value}) {
  const attribute = attributeOf(node, name)
  return attribute.kind === "present" && attribute.value === value
}

// A rule of html-eslint that passes over the tags `isExempt` names and
// checks every other one as the rule does.
function exempting({rule, isExempt}) {
  return {
    ...rule,
    create(context) {
      const visitors = rule.create(context)
      const wrapped = {}

      for (const [key, visit] of Object.entries(visitors)) {
        wrapped[key] = (node) => {
          const isTag = node.type === "Tag"
          const isSkipped = isTag && isExempt(node)

          if (!isSkipped) {
            visit(node)
          }
        }
      }

      return wrapped
    }
  }
}

// A live region is empty until the page has something to announce, and a
// region that is added already holding its text is not announced, so an
// empty status or live paragraph is the pattern, not a missing content.
// https://www.w3.org/WAI/ARIA/apg/practices/live-regions/ — checked 2026-11-09
function isLiveRegion(node) {
  const isStatus = isAttributeValue({node, name: "role", value: "status"})
  return isStatus || hasAttribute(node, "aria-live")
}

// LiveView sends a form's change and submit events over its socket, so its
// `method` decides nothing.
function isLiveViewForm(node) {
  return hasAttribute(node, "phx-submit") || hasAttribute(node, "phx-change")
}

// The web app manifest link and the theme color are hints a browser that
// does not know them ignores; use-baseline judges browser support, which
// for these two costs no rider anything.
function isProgressiveHint(node) {
  const isManifest = isAttributeValue({node, name: "rel", value: "manifest"})
  return isManifest || isAttributeValue({node, name: "name", value: "theme-color"})
}

const htmlRules = html.rules

const local = {
  rules: {
    "require-content": exempting({rule: htmlRules["require-content"], isExempt: isLiveRegion}),
    "require-form-method": exempting({rule: htmlRules["require-form-method"], isExempt: isLiveViewForm}),
    "use-baseline": exempting({rule: htmlRules["use-baseline"], isExempt: isProgressiveHint})
  }
}

